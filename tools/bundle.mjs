import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.resolve(__dirname, "..");
const SRC_DIR = path.join(ROOT_DIR, "src");
const DIST_DIR = path.join(ROOT_DIR, "dist");

const LAYER_ORDER = [
	"Generated",
	"Core",
	"Systems",
	"Elements",
	"Window",
	"Builders",
];

function walkLuaFiles(dirPath) {
	const results = [];
	if (!fs.existsSync(dirPath)) {
		return results;
	}
	for (const entry of fs.readdirSync(dirPath, { withFileTypes: true })) {
		const fullPath = path.join(dirPath, entry.name);
		if (entry.isDirectory()) {
			results.push(...walkLuaFiles(fullPath));
		} else if (entry.isFile() && entry.name.endsWith(".lua")) {
			results.push(fullPath);
		}
	}
	return results;
}

function toModuleName(filePath) {
	const rel = path.relative(SRC_DIR, filePath).replace(/\\/g, "/");
	return rel.replace(/\.lua$/, "");
}

function sortModules(files) {
	return [...files].sort((a, b) => {
		const nameA = toModuleName(a);
		const nameB = toModuleName(b);

		const topA = nameA.includes("/") ? nameA.split("/")[0] : "";
		const topB = nameB.includes("/") ? nameB.split("/")[0] : "";

		const rankA = LAYER_ORDER.indexOf(topA);
		const rankB = LAYER_ORDER.indexOf(topB);

		const effA = rankA === -1 ? (nameA === "Lumina" ? 100 : nameA === "Example" ? 101 : 99) : rankA;
		const effB = rankB === -1 ? (nameB === "Lumina" ? 100 : nameB === "Example" ? 101 : 99) : rankB;

		if (effA !== effB) {
			return effA - effB;
		}
		return nameA.localeCompare(nameB);
	});
}

function readCleanSource(filePath) {
	let text = fs.readFileSync(filePath, "utf8");
	if (text.charCodeAt(0) === 0xfeff) {
		text = text.slice(1);
	}
	return text.replace(/\r\n/g, "\n").replace(/\n+$/, "");
}

function buildBundle({ modules, footer, banner }) {
	const parts = [];

	parts.push(
		`--[[\n${banner}\n]]\n\n` +
			`local __origRequire = require\n` +
			`local __modules = {}\n` +
			`local __cache = {}\n` +
			`local __loading = {}\n\n` +
			`local function require(name)\n` +
			`\tif type(name) ~= "string" then\n` +
			`\t\tif __origRequire then\n` +
			`\t\t\treturn __origRequire(name)\n` +
			`\t\tend\n` +
			`\t\terror("[Lumina] Invalid module argument to require: " .. tostring(name), 2)\n` +
			`\tend\n` +
			`\tlocal cached = __cache[name]\n` +
			`\tif cached ~= nil then\n` +
			`\t\treturn cached\n` +
			`\tend\n` +
			`\tlocal loader = __modules[name]\n` +
			`\tif not loader then\n` +
			`\t\terror("[Lumina] Unknown bundled module: " .. tostring(name), 2)\n` +
			`\tend\n` +
			`\tif __loading[name] then\n` +
			`\t\terror("[Lumina] Circular require detected for module: " .. tostring(name), 2)\n` +
			`\tend\n` +
			`\t__loading[name] = true\n` +
			`\tlocal result = loader()\n` +
			`\t__loading[name] = nil\n` +
			`\tif result == nil then\n` +
			`\t\tresult = true\n` +
			`\tend\n` +
			`\t__cache[name] = result\n` +
			`\treturn result\n` +
			`end\n`
	);

	// Wrap raw Luau bodies directly inside functions so multiline [[...]] strings in
	// AssetData.lua or Example.lua never require string escaping or indentation edits.
	for (const filePath of modules) {
		const modName = toModuleName(filePath);
		const body = readCleanSource(filePath);
		parts.push(`__modules[${JSON.stringify(modName)}] = function()\n${body}\nend\n`);
	}

	parts.push(`${footer}\n`);
	return parts.join("\n");
}

function main() {
	const allFiles = sortModules(walkLuaFiles(SRC_DIR));
	if (allFiles.length === 0) {
		throw new Error(`No .lua files found inside ${SRC_DIR}`);
	}

	const libraryModules = allFiles.filter((filePath) => toModuleName(filePath) !== "Example");
	const exampleModules = allFiles;

	fs.mkdirSync(DIST_DIR, { recursive: true });

	const libBundle = buildBundle({
		modules: libraryModules,
		banner: `\tLumina UI v1.0.0 — Self-Contained Library Bundle\n\tGenerated by tools/bundle.mjs (${libraryModules.length} modules)`,
		footer: `return require("Lumina")`,
	});

	const exampleBundle = buildBundle({
		modules: exampleModules,
		banner: `\tLumina UI v1.0.0 — Complete Interactive Showcase Bundle\n\tGenerated by tools/bundle.mjs (${exampleModules.length} modules)`,
		footer: `require("Example")`,
	});

	const libOut = path.join(DIST_DIR, "Lumina.lua");
	const exampleOut = path.join(DIST_DIR, "LuminaExample.lua");

	fs.writeFileSync(libOut, libBundle, "utf8");
	fs.writeFileSync(exampleOut, exampleBundle, "utf8");

	const formatKb = (bytes) => `${(bytes / 1024).toFixed(1)} KB`;
	console.log(`Bundled ${libraryModules.length} modules -> dist/Lumina.lua (${formatKb(Buffer.byteLength(libBundle, "utf8"))})`);
	console.log(`Bundled ${exampleModules.length} modules -> dist/LuminaExample.lua (${formatKb(Buffer.byteLength(exampleBundle, "utf8"))})`);
}

main();
